package com.project.entity;

public enum VideoStatus {
    /**
     * Идёт автопроверка (длительность, обложка, речь, кадры)
     */
    PROCESSING,
    /**
     * Проверка пройдена или одобрено админом.
     */
    PUBLISHED,
    /**
     * Автопроверка нашла подозрительное - ждёт решения админа.
     */
    ON_REVIEW,
    /**
     * Отклонено админом.
     */
    REJECTED
}
